'use strict';

/**
 * api 子模块（KuGouMusicApi, MIT）安装期补丁。
 *
 * 补丁内容：/everyday/recommend（module/everyday_recommend.js）上游只发固定
 * POST 体（仅 platform），丢弃渲染进程传入的分页参数，导致普通账号每日推荐
 * 永远只有一页 30 首。这里整文件重写该模块，把 pagesize/page 从请求参数
 * 透传给酷狗接口；带 JELLO_DAILY_PAGING_PATCH 标记保证幂等。
 *
 * 约束：
 * - 只在 `npm install`（postinstall）/ `npm run install-all` 时执行，不改子模块 git 历史；
 * - 子模块缺失（CI 未 checkout submodule）、文件已被上游改版认不出、读写失败等
 *   任何异常都只打警告并以 0 退出——补丁永远不能弄坏安装。
 *
 * 用法：node tools/patch-api.cjs [--api-dir <dir>] [--dry-run]
 */

const fs = require('fs');
const path = require('path');

const MARKER = 'JELLO_DAILY_PAGING_PATCH';
const TARGET_REL = path.join('module', 'everyday_recommend.js');
// 认锚点再覆盖：上游若改了接口路径说明模块已重构，补丁不再适用，跳过而不是瞎覆盖
const UPSTREAM_ANCHOR = '/everyday_song_recommend';

const PATCHED_SOURCE = `// ${MARKER}
// Generated by tools/patch-api.cjs (Jello Music install-time patch).
// Forwards pagesize/page so /everyday/recommend can be paged beyond 30 songs;
// the upstream module sends a fixed body with only \`platform\`.
module.exports = (params, useAxios) => {
  const extra = {};
  for (const key of ['pagesize', 'page']) {
    const value = params == null ? undefined : params[key];
    if (value === undefined || value === null || value === '') continue;
    const num = Number(value);
    extra[key] = Number.isFinite(num) ? num : value;
  }

  return useAxios({
    url: '${UPSTREAM_ANCHOR}',
    encryptType: 'android',
    method: 'POST',
    params: Object.assign({ platform: (params && params.platform) || 'ios' }, extra),
    cookie: (params && params.cookie) || {},
    headers: { 'x-router': 'everydayrec.service.kugou.com' },
  });
};
`;

const isPatched = (source) => typeof source === 'string' && source.includes(MARKER);

/**
 * 对 apiDir 下的 everyday_recommend.js 应用补丁。
 * 返回 { status, target, message? }，status ∈
 * patched | already | missing | unrecognized | dry-run | error。绝不抛异常之外的副作用。
 */
function patchEverydayRecommend(apiDir, options = {}) {
  const target = path.join(apiDir, TARGET_REL);
  if (!fs.existsSync(target)) return { status: 'missing', target };

  let current;
  try {
    current = fs.readFileSync(target, 'utf8');
  } catch (error) {
    return { status: 'error', target, message: error.message };
  }

  if (isPatched(current)) return { status: 'already', target };
  if (!current.includes(UPSTREAM_ANCHOR)) return { status: 'unrecognized', target };
  if (options.dryRun) return { status: 'dry-run', target };

  try {
    fs.writeFileSync(target, PATCHED_SOURCE, 'utf8');
  } catch (error) {
    return { status: 'error', target, message: error.message };
  }
  return { status: 'patched', target };
}

function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const dirIndex = args.indexOf('--api-dir');
  const apiDir = dirIndex >= 0 && args[dirIndex + 1]
    ? path.resolve(args[dirIndex + 1])
    : path.resolve(__dirname, '..', 'api');

  let result;
  try {
    result = patchEverydayRecommend(apiDir, { dryRun });
  } catch (error) {
    console.warn(`[patch-api] 补丁异常（不影响安装）: ${error.message}`);
    return;
  }

  switch (result.status) {
    case 'patched':
      console.log('[patch-api] 已应用每日推荐分页补丁:', result.target);
      break;
    case 'already':
      console.log('[patch-api] 每日推荐分页补丁已存在，跳过');
      break;
    case 'missing':
      console.log('[patch-api] 未找到 api 子模块文件，跳过（submodule 未初始化？）');
      break;
    case 'unrecognized':
      console.warn('[patch-api] everyday_recommend.js 与预期上游不符，跳过以免误覆盖');
      break;
    case 'dry-run':
      console.log('[patch-api] dry-run：将改写', result.target);
      break;
    default:
      console.warn(`[patch-api] 补丁失败（不影响安装）: ${result.message || result.status}`);
  }
}

if (require.main === module) main();

module.exports = { MARKER, PATCHED_SOURCE, UPSTREAM_ANCHOR, isPatched, patchEverydayRecommend };
